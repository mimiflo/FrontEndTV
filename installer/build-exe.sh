#!/usr/bin/env bash
# Builds FrontEndTV-Installateur.exe (installer/*.cs) for the FrontEndTV.apk at the top of the repository (build.sh
# calls it; GitHub builds it on Windows). The APK is not inside: the installer takes the one next to it, or downloads
# this version's from the GitHub Release, and checks its SHA-256 (out/BuildInfo.cs).
# Compiled with the csc.exe that comes with Windows (Git Bash or WSL), or Mono's mcs elsewhere.
set -euo pipefail
cd "$(dirname "$0")/.."
[ -f FrontEndTV.apk ] || { echo "FrontEndTV.apk not found: run build.sh first."; exit 1; }

CSC=""
for c in /c/Windows/Microsoft.NET/Framework64/v4.0.30319/csc.exe /mnt/c/Windows/Microsoft.NET/Framework64/v4.0.30319/csc.exe \
         /c/Windows/Microsoft.NET/Framework/v4.0.30319/csc.exe /mnt/c/Windows/Microsoft.NET/Framework/v4.0.30319/csc.exe; do
  if [ -f "$c" ]; then CSC="$c"; break; fi
done
if [ -z "$CSC" ] && command -v mcs >/dev/null; then CSC=mcs; fi
if [ -z "$CSC" ]; then
  echo "No C# compiler (Windows' csc.exe, or Mono's mcs): FrontEndTV-Installateur.exe not built."
  exit 0
fi

mkdir -p out
VERSION="$(grep -o 'android:versionName="[^"]*"' app/AndroidManifest.xml | cut -d'"' -f2)"
REPO="$(grep -E '^[[:space:]]*update_repo[[:space:]]*=' config.properties 2>/dev/null | tail -1 | cut -d= -f2- | tr -d ' "\r' || true)"
REPO="${REPO:-mimiflo/FrontEndTV}"
SHA="$(sha256sum FrontEndTV.apk | cut -d' ' -f1)"
cat > out/BuildInfo.cs <<EOF
// Generated by installer/build-exe.sh: the version this installer installs, and where to find its APK.
namespace FrontEndTV.Setup {
static class BuildInfo {
    public const string Version = "$VERSION";
    public const string ApkUrl = "https://github.com/$REPO/releases/download/v$VERSION/FrontEndTV.apk";
    public const string ApkSha256 = "$SHA";
}
}
EOF

# The app's icon in every size Windows uses (16 to 192 px), for the .exe and its window
JAVA=java; command -v java >/dev/null || JAVA="$JAVA_HOME/bin/java"
"$JAVA" installer/MakeIcon.java app/res/drawable-nodpi/icon.png out/app.ico
# -codepage: Windows' csc otherwise reads the sources in the ANSI code page (the accents). Mono's mcs has no
# -win32manifest; its .exe only differs by that (SetProcessDPIAware does the same at start).
EXTRA="-codepage:65001 -win32manifest:installer/app.manifest"; [ "$CSC" = mcs ] && EXTRA=
"$CSC" -nologo $EXTRA -optimize+ -target:winexe -win32icon:out/app.ico \
  -r:System.Windows.Forms.dll -r:System.Drawing.dll -r:System.Numerics.dll \
  -resource:app/res/drawable-nodpi/icon.png,icon.png -resource:out/app.ico,app.ico \
  -out:FrontEndTV-Installateur.exe installer/Program.cs installer/Engine.cs installer/Adb.cs out/BuildInfo.cs
echo "Built FrontEndTV-Installateur.exe ($(du -h FrontEndTV-Installateur.exe | cut -f1)) for FrontEndTV $VERSION."
